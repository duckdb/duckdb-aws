#!/usr/bin/env bash

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
source "$PROJECT_ROOT/scripts/test_aws_credentials.sh"

export AWS_REGION="${AWS_REGION:-${AWS_DEFAULT_REGION:-eu-central-1}}"
PREFIX="${PREFIX:-$(id -un)}"
DATA_URL="${S3_DATA_URL:-https://blobs.duckdb.org/nl-railway/services-2025-03.csv.gz}"
OBJECT_KEY="${S3_OBJECT_KEY:-nl-railway/services-2025-03.csv.gz}"
FIXTURE_KEY="duckdb-fixture/data.csv.gz"
ENV_FILE="${S3_ENV_FILE:-$PROJECT_ROOT/test/sql/s3/s3.env}"
MANAGED_BY="duckdb-aws-s3-test"
BUCKET="${S3_BUCKET_NAME:-}"
FORCE=false

parse_args() {
	while (($#)); do
		case "$1" in
			--force) FORCE=true ;;
			-h|--help) usage; exit 0 ;;
			*) echo "Unknown argument: $1" >&2; usage >&2; exit 2 ;;
		esac
		shift
	done
}

validate_configuration() {
	if [[ ! "$PREFIX" =~ ^[a-z0-9][a-z0-9-]*$ || ! "$AWS_REGION" =~ ^[a-z0-9-]+$ ]]; then
		echo "PREFIX and AWS_REGION must contain lowercase letters, digits, and hyphens" >&2
		return 1
	fi
	if [[ -n "$BUCKET" ]] && { ((${#BUCKET} < 3 || ${#BUCKET} > 63)) || [[ ! "$BUCKET" =~ ^[a-z0-9][a-z0-9-]*[a-z0-9]$ ]]; }; then
		echo "S3_BUCKET_NAME must be 3-63 lowercase letters, digits or hyphens, starting and ending with a letter or digit" >&2
		return 1
	fi
	case "$BUCKET" in
		xn--*|sthree-*|amzn-s3-demo-*|*-s3alias|*--ol-s3|*--x-s3|*--table-s3|*--xa-s3)
			echo "S3_BUCKET_NAME uses a reserved prefix or suffix" >&2; return 1 ;;
	esac
	if [[ ! "$OBJECT_KEY" =~ ^[a-zA-Z0-9][a-zA-Z0-9/_.-]*$ || "$OBJECT_KEY" == "$FIXTURE_KEY" ]]; then
		echo "S3_OBJECT_KEY must be a distinct simple object path" >&2
		return 1
	fi
	if [[ "$DATA_URL" != https://* ]]; then
		echo "S3_DATA_URL must use HTTPS" >&2
		return 1
	fi
}

resolve_identity() {
	fixture_credentials
	AWS_ACCOUNT_ID=$(aws sts get-caller-identity --query Account --output text)
	if [[ ! "$AWS_ACCOUNT_ID" =~ ^[0-9]{12}$ ]]; then
		echo "Cannot determine the AWS account" >&2
		return 1
	fi
	BUCKET="${BUCKET:-$PREFIX-duckdb-aws-$AWS_ACCOUNT_ID-$AWS_REGION}"
	validate_configuration
}

s3api() {
	aws --region "$AWS_REGION" --no-cli-pager s3api "$@"
}

bucket_exists() {
	local result
	if result=$(s3api head-bucket --bucket "$BUCKET" --expected-bucket-owner "$AWS_ACCOUNT_ID" 2>&1); then
		return 0
	elif [[ "$result" == *'(404)'* || "$result" == *'(NoSuchBucket)'* || "$result" == *'(NotFound)'* ]]; then
		return 1
	else
		echo "$result" >&2
		return 2
	fi
}

assert_managed_bucket() {
	local tags region versioning
	tags=$(s3api get-bucket-tagging --bucket "$BUCKET" --expected-bucket-owner "$AWS_ACCOUNT_ID" --output json)
	if ! jq -e --arg owner "$MANAGED_BY" \
		'any(.TagSet[]; .Key == "ManagedBy" and .Value == $owner) and any(.TagSet[]; .Key == "Project" and .Value == "duckdb-aws")' \
		>/dev/null <<<"$tags"; then
		echo "Bucket $BUCKET is not managed by this fixture; refusing to modify it" >&2
		return 1
	fi
	region=$(s3api get-bucket-location --bucket "$BUCKET" --expected-bucket-owner "$AWS_ACCOUNT_ID" --output json | jq -r '.LocationConstraint // "us-east-1"')
	[[ "$region" != EU ]] || region=eu-west-1
	if [[ "$region" != "$AWS_REGION" ]]; then
		echo "Bucket region does not match AWS_REGION" >&2
		return 1
	fi
	versioning=$(s3api get-bucket-versioning --bucket "$BUCKET" --expected-bucket-owner "$AWS_ACCOUNT_ID" --output json)
	if ! jq -e '.Status == null' >/dev/null <<<"$versioning"; then
		echo "Versioned or suspended buckets require manual cleanup; refusing to modify one" >&2
		return 1
	fi
}

assert_only_fixture_objects() {
	local objects
	objects=$(s3api list-objects-v2 --bucket "$BUCKET" --expected-bucket-owner "$AWS_ACCOUNT_ID" --output json)
	if ! jq -e --arg fixture "$FIXTURE_KEY" --arg railway "$OBJECT_KEY" \
		'all(.Contents[]?; .Key == $fixture or .Key == $railway)' >/dev/null <<<"$objects"; then
		echo "Bucket contains unrelated objects; refusing cleanup" >&2
		return 1
	fi
}

write_environment() {
	mkdir -p "$(dirname "$ENV_FILE")"
	(umask 077; {
		printf '# Generated by scripts/s3/create_bucket.sh; contains no AWS secrets.\n'
		printf 'unset S3_TEST_AVAILABLE\n'
		printf 'export AWS_REGION=%q\n' "$AWS_REGION"
		printf 'export PREFIX=%q\n' "$PREFIX"
		printf 'export S3_ENV_FILE=%q\n' "$ENV_FILE"
		printf 'export S3_BUCKET_NAME=%q\n' "$BUCKET"
		printf 'export S3_OBJECT_KEY=%q\n' "$OBJECT_KEY"
		printf 'export AWS_S3_BUCKET=%q\n' "$BUCKET"
		printf 'export AWS_S3_OBJECT_KEY=%q\n' "$OBJECT_KEY"
		printf 'export AWS_S3_FIXTURE_KEY=%q\n' "$FIXTURE_KEY"
		fixture_write_credentials
		printf 'export S3_TEST_AVAILABLE=1\n'
	} >"$ENV_FILE")
	chmod 600 "$ENV_FILE"
}

disable_environment() {
	local quoted_bucket quoted_key
	printf -v quoted_bucket '%q' "$BUCKET"
	printf -v quoted_key '%q' "$OBJECT_KEY"
	if [[ -f "$ENV_FILE" ]] &&
		grep -Fxq '# Generated by scripts/s3/create_bucket.sh; contains no AWS secrets.' "$ENV_FILE" &&
		grep -Fxq "export AWS_S3_BUCKET=$quoted_bucket" "$ENV_FILE" &&
		grep -Fxq "export AWS_S3_OBJECT_KEY=$quoted_key" "$ENV_FILE"; then
		rm -- "$ENV_FILE"
		echo "Removed $ENV_FILE; unset S3_TEST_AVAILABLE in shells that already sourced it"
	fi
}
